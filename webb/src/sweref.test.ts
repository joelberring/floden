test("40 punkter mot pyproj: WGS 84 till SWEREF 99 18 00 inom 1 mm (kravet är 1 cm)", () => {
  let storst = 0;
  for (const [lon, lat, e, n] of PYPROJ) {
    const [e2, n2] = wgs84TillSweref(lon, lat);
    storst = Math.max(storst, Math.hypot(e2 - e, n2 - n));
  }
  assert.ok(storst < 0.001, `största avvikelse ${storst} m`);
});

test("40 punkter mot pyproj: SWEREF till WGS 84 inom 1e-9 grader (0,1 mm) och tur och retur", () => {
  for (const [lon, lat, e, n] of PYPROJ) {
    const [lo, la] = swerefTillWgs84(e, n);
    assert.ok(Math.abs(lo - lon) < 1e-9 && Math.abs(la - lat) < 1e-9, `${lon},${lat}: ${lo},${la}`);
  }
});

test("WGS 84 till SWEREF 99 18 00 stämmer med pyproj inom 1 mm", () => {
  for (const [lon, lat, e, n] of FACIT) {
    const [e2, n2] = wgs84TillSweref(lon, lat);
    assert.ok(Math.abs(e2 - e) < 0.001, `E ${e2} mot ${e}`);
    assert.ok(Math.abs(n2 - n) < 0.001, `N ${n2} mot ${n}`);
  }
});

test("SWEREF till WGS 84 och tillbaka ger samma punkt", () => {
  for (const [, , e, n] of FACIT) {
    const [lon, lat] = swerefTillWgs84(e, n);
    const [e2, n2] = wgs84TillSweref(lon, lat);
    assert.ok(Math.abs(e2 - e) < 0.001 && Math.abs(n2 - n) < 0.001);
  }
});
